"""Rebuild web/js/learn-data.js (the "Learn more" pages).

It copies each tool's Python code straight out of python-flask/processing.py, so the
code shown in the app is always exactly what the Flask version runs, and adds the
theory text from scripts/learn_theory.py.

    python scripts/build_learn_data.py
"""
import ast
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "python-flask" / "processing.py"
OUT = ROOT / "web" / "js" / "learn-data.js"

# which functions from processing.py belong to each tool (helpers first)
TOOL_FUNCTIONS = {
    "brightness_contrast": ["brightness_contrast"], "gamma": ["gamma"], "negative": ["negative"],
    "stretch": ["contrast_stretch"], "equalize": ["to_gray", "hist_equalize"], "clahe": ["to_gray", "clahe"],
    "log": ["log_transform"], "bitplane": ["to_gray", "bit_plane"],
    "crop": ["crop"], "resize": ["resize"], "rotate": ["rotate"], "flip": ["flip"],
    "mean": ["make_odd", "mean_filter"], "gaussian": ["make_odd", "gaussian_filter"],
    "median": ["make_odd", "median_filter"], "bilateral": ["bilateral_filter"], "noise": ["gaussian_noise"],
    "sobel": ["to_gray", "to_uint8", "sobel"], "prewitt": ["to_gray", "to_uint8", "prewitt"],
    "roberts": ["to_gray", "to_uint8", "roberts"], "canny": ["to_gray", "canny"],
    "laplacian": ["to_gray", "to_uint8", "laplacian"],
    "hsi_component": ["rgb_to_hsi", "hsi_component"], "hsi_roundtrip": ["rgb_to_hsi", "hsi_to_rgb", "hsi_roundtrip"],
    "colorspace": ["SPACES", "color_space"], "channel": ["rgb_channel"],
    "sample": ["sample"], "quantize": ["quantize"], "components": ["to_gray", "components"],
    "threshold": ["to_gray", "threshold"], "kmeans": ["kmeans"], "morph": ["to_gray", "make_odd", "morph"],
    "fft": ["to_gray", "to_uint8", "fft_tool"], "match": ["match_hist"], "compare": ["to_gray", "compare"],
}


def main():
    src = SRC.read_text(encoding="utf-8")
    funcs = {}
    for node in ast.parse(src).body:
        if isinstance(node, ast.FunctionDef):
            funcs[node.name] = ast.get_source_segment(src, node)
        elif isinstance(node, ast.Assign):
            funcs[node.targets[0].id] = ast.get_source_segment(src, node)

    spec = importlib.util.spec_from_file_location("learn_theory", ROOT / "scripts" / "learn_theory.py")
    theory = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(theory)

    data = {}
    for tool, names in TOOL_FUNCTIONS.items():
        code = "import cv2\nimport numpy as np\n\n\n" + "\n\n\n".join(funcs[n] for n in names)
        data[tool] = dict(theory.T[tool], code=code)

    OUT.write_text(
        "// Learn-more pages: theory for every tool + the real Python/OpenCV code from processing.py\n"
        "// (generated by scripts/build_learn_data.py - edit that script or learn_theory.py, not this file)\n"
        "window.LEARN = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data)} tools)")


if __name__ == "__main__":
    main()
